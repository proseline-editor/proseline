// Writes (or with --check, verifies) api/<package>.api.md: every public export of every published
// package, read from the built type declarations. A change to the public API shows up as a diff of
// these files in review, and CI fails when they are out of date.
// With --docs <dir>, writes the documentation site's API reference instead: the same exports with
// their TSDoc comments, one page per package.
import { readFileSync, writeFileSync, readdirSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const docsAt = process.argv.indexOf('--docs');
const docsDir = docsAt >= 0 ? resolve(root, process.argv[docsAt + 1] ?? 'site/reference') : null;
const outDir = docsDir ?? join(root, 'api');

const entriesOf = (pkgDir) => {
  const pkg = JSON.parse(readFileSync(join(pkgDir, 'package.json'), 'utf8'));
  const description = pkg.description ?? '';
  const entries = [];
  for (const [subpath, target] of Object.entries(pkg.exports ?? {})) {
    // Wildcards repeat what the barrel exports; stylesheets have no API.
    if (subpath.includes('*') || typeof target !== 'object' || !target.types) continue;
    entries.push({ subpath, file: join(pkgDir, target.types) });
  }
  return { name: pkg.name, description, entries };
};

const printer = ts.createPrinter({ removeComments: true, newLine: ts.NewLineKind.LineFeed });

const describe = (checker, symbol) => {
  const target = symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol;
  const decl = target.declarations?.[0];
  if (!decl) return `${symbol.name}: unknown`;
  if (ts.isVariableDeclaration(decl) || ts.isFunctionDeclaration(decl)) {
    const type = checker.getTypeOfSymbolAtLocation(target, decl);
    return `const ${symbol.name}: ${checker.typeToString(type, undefined, ts.TypeFormatFlags.NoTruncation)};`;
  }
  // Types, interfaces, classes and enums: their declaration, without comments, under the exported name.
  const text = printer.printNode(ts.EmitHint.Unspecified, decl, decl.getSourceFile());
  return symbol.name === target.name ? text : `${text} // exported as ${symbol.name}`;
};

/** TSDoc summary of an export, made safe for the docs site (raw `<` outside code would be read as HTML). */
const docOf = (checker, symbol) => {
  const target = symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol;
  const text = ts.displayPartsToString(target.getDocumentationComment(checker)).trim();
  return text
    .split('`')
    .map((part, i) => (i % 2 ? part : part.replace(/</g, '&lt;')))
    .join('`');
};

/** One reference page: every entry point, every export with its comment and declaration. */
const reference = ({ name, description, entries }) => {
  const files = entries.map((e) => e.file);
  const program = ts.createProgram(files, { module: ts.ModuleKind.NodeNext, moduleResolution: ts.ModuleResolutionKind.NodeNext, target: ts.ScriptTarget.ES2022, skipLibCheck: true, noEmit: true });
  const checker = program.getTypeChecker();
  let out = `# ${name}\n\n${description}\n\nGenerated from the type declarations by \`pnpm api:docs\`.\n\n::: v-pre\n`;
  for (const { subpath, file } of entries) {
    const source = program.getSourceFile(file);
    if (!source) throw new Error(`${name}: missing ${file} (run pnpm build first)`);
    const exports = checker.getExportsOfModule(checker.getSymbolAtLocation(source)).sort((a, b) => a.name.localeCompare(b.name));
    out += `\n## \`${subpath === '.' ? name : name + subpath.slice(1)}\`\n`;
    for (const symbol of exports) {
      const doc = docOf(checker, symbol);
      out += `\n### ${symbol.name}\n\n${doc ? doc + '\n\n' : ''}\`\`\`ts\n${describe(checker, symbol)}\n\`\`\`\n`;
    }
  }
  return out + '\n:::\n';
};

const report = ({ name, entries }) => {
  const files = entries.map((e) => e.file);
  const program = ts.createProgram(files, { module: ts.ModuleKind.NodeNext, moduleResolution: ts.ModuleResolutionKind.NodeNext, target: ts.ScriptTarget.ES2022, skipLibCheck: true, noEmit: true });
  const checker = program.getTypeChecker();
  let out = `# API report: ${name}\n\nGenerated by \`pnpm api:update\` from the built declarations. Do not edit.\n`;
  for (const { subpath, file } of entries) {
    const source = program.getSourceFile(file);
    if (!source) throw new Error(`${name}: missing ${file} (run pnpm build first)`);
    const exports = checker.getExportsOfModule(checker.getSymbolAtLocation(source)).sort((a, b) => a.name.localeCompare(b.name));
    out += `\n## \`${subpath === '.' ? name : name + subpath.slice(1)}\`\n\n\`\`\`ts\n${exports.map((s) => describe(checker, s)).join('\n\n')}\n\`\`\`\n`;
  }
  return out;
};

const packages = readdirSync(join(root, 'packages')).map((d) => join(root, 'packages', d)).filter((d) => existsSync(join(d, 'package.json')));
mkdirSync(outDir, { recursive: true });
let stale = [];
for (const dir of packages) {
  const info = entriesOf(dir);
  if (!info.entries.length) continue;
  const slug = info.name.replace('@proseline-editor/', '');
  const file = join(outDir, docsDir ? `${slug}.md` : `${slug}.api.md`);
  const text = docsDir ? reference(info) : report(info);
  if (check) {
    if (!existsSync(file) || readFileSync(file, 'utf8') !== text) stale.push(file.slice(root.length + 1));
  } else {
    writeFileSync(file, text);
  }
}
if (stale.length) {
  process.stderr.write(`The public API changed: ${stale.join(', ')}.\nRun \`pnpm api:update\`, review the diff and commit it (with a changeset).\n`);
  process.exit(1);
}
process.stdout.write(check ? 'API reports are up to date.\n' : `API ${docsDir ? 'reference' : 'reports'} written to ${outDir.slice(root.length + 1)}/.\n`);
